/** The page of the book a number stands on, or null. */
export function abokPagina(nummer) {
  const n = Number(nummer);
  if (!Number.isInteger(n) || n < 1 || n > 3900) return null;
  let lo = 0; let hi = PAGINAS.length - 1;
  while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (PAGINAS[mid][0] <= n) lo = mid; else hi = mid - 1; }
  return PAGINAS[lo][1];
}

/** The scan on archive.org, open at the page of the number (or at its start). */
export const abokLink = (nummer) => { const p = abokPagina(nummer); return p ? `${SCAN}/page/${p}/mode/2up` : SCAN; };
